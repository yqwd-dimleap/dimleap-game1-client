import { ResourceScope } from './ResourceScope';
import type { ResourceLoader } from './ResourceScope';
export type { ResourceLoader } from './ResourceScope';
import { Asset, AssetManager, assetManager, Constructor, SceneAsset } from 'cc';
import { AppConfig } from './Config';
import type { Platform } from '../sdk/Platform';
import { DEBUG, EDITOR, PREVIEW } from 'cc/env';
import { LoadQueue, LoadPriority, LoadQueueSnapshot } from './LoadQueue';
import { RemoteVersionManager, remoteBundleUrl } from './RemoteVersion';
import type { RemoteVersionSnapshot, RemoteVersionStorage } from './RemoteVersion';

export type LoadProgress = (finished: number, total: number) => void;
export interface ResMetrics {
    queue: LoadQueueSnapshot;
    bundleRequests: number;
    assetRequests: number;
    remoteVersion: RemoteVersionSnapshot;
}
interface SharedAssetLoad {
    promise: Promise<Asset>;
    cancellations: Set<() => boolean>;
}

function missingBundle(error: unknown): string | undefined {
    const message = error instanceof Error ? error.message : String(error);
    return /Please load bundle ([a-z][a-z0-9_]*) first/.exec(message)?.[1];
}

/** Bundle names are loading boundaries. No scene or prefab references cross the bootstrap boundary. */
export class Res {
    private pending = new Map<string, Promise<AssetManager.Bundle>>();
    private assets = new Map<Constructor<Asset>, Map<string, SharedAssetLoad>>();
    private queue = new LoadQueue(6);
    private versions: RemoteVersionManager;
    readonly application: ResourceScope;
    constructor(private config: AppConfig, private platform: Platform, storage: RemoteVersionStorage) {
        this.versions = new RemoteVersionManager(
            config.remoteBaseUrl[platform.kind],
            config.remoteVersion,
            platform,
            storage,
            !(PREVIEW || EDITOR),
        );
        this.application = this.createScope('application');
    }
    initialize(): Promise<RemoteVersionSnapshot> {
        return this.versions.initialize();
    }
    get remoteVersion(): RemoteVersionSnapshot { return this.versions.state; }
    createScope(name: string): ResourceScope {
        const loader: ResourceLoader = {
            load: (bundle, path, type, progress, priority, cancelled) =>
                this.loadAsset(bundle, path, type, progress, priority, cancelled),
        };
        return new ResourceScope(name, loader);
    }
    /** Explicit app-lifetime cache; scenes and views must load through their own scope. */
    load<T extends Asset>(bundle: string, path: string, type: Constructor<T>, progress?: LoadProgress,
        priority?: LoadPriority): Promise<T> {
        return this.application.load(bundle, path, type, progress, priority);
    }
    metrics(): ResMetrics {
        let assetRequests = 0;
        for (const pending of this.assets.values()) assetRequests += pending.size;
        return { queue: this.queue.snapshot(), bundleRequests: this.pending.size, assetRequests,
            remoteVersion: this.versions.state };
    }
    isBundleLoaded(name: string): boolean { return !!assetManager.getBundle(name); }
    async bundle(name: string): Promise<AssetManager.Bundle> {
        await this.versions.initialize();
        const cached = assetManager.getBundle(name);
        if (cached) return Promise.resolve(cached);
        const inflight = this.pending.get(name);
        if (inflight) return inflight;
        const definition = this.config.bundles[name];
        if (!definition) return Promise.reject(new Error(`未声明资源包：${name}`));
        const remote = definition.delivery === 'remote';
        const base = this.config.remoteBaseUrl[this.platform.kind];
        // Both browser preview and the editor Game View generate local bundle URLs.
        const localPreview = PREVIEW || EDITOR;
        // A local preview can use its generated bundle URL. Published remote content needs a real CDN.
        if (remote && !base && !localPreview) return Promise.reject(new Error(`远程资源 ${name} 尚未配置 CDN`));
        // Bundle versions come from the engine settings generated by the same build as the remote
        // bundles; pinning them in app.json drifts after every rebuild and 404s the config fetch.
        const options: { version?: string } = {};
        const label = remote && !localPreview ? 'remote' : 'local';
        const task = this.ensureDependencies(definition.dependencies).then(async () => {
            if (remote && !localPreview) {
                const versions = this.versions.recoveryVersionsForBundle(name);
                const failures: string[] = [];
                for (const version of versions) {
                    const source = remoteBundleUrl(base, name, version);
                    console.info(`[Res] remote ${name} -> version=${version} | ${source}`);
                    try {
                        const bundle = await this.loadBundleSource(source, options);
                        await this.ensureDependencies(bundle.deps || []);
                        this.versions.markLoaded(name, version);
                        if (DEBUG) console.info(`[Res] bundle ${name} (${label}) ready from ${source}`);
                        return bundle;
                    } catch (error) {
                        const message = error instanceof Error ? error.message : String(error);
                        failures.push(`${version}: ${message}`);
                        console.warn(`[Res] bundle ${name} (${label}) failed at ${source}: ${message}`);
                    }
                }
                throw new Error(`资源包 ${name} 加载失败：${failures.join(' | ')}`);
            }
            const bundle = await this.loadBundleSource(name, options);
            // The generated bundle metadata is authoritative. It can contain a dependency
            // that is newer than app.json during a partial rollout, and WeChat resolves
            // redirected assets lazily while the first prefab is parsed.
            await this.ensureDependencies(bundle.deps || []);
            if (DEBUG) console.info(`[Res] bundle ${name} (${label}) ready`);
            return bundle;
        });
        this.pending.set(name, task);
        const clear = (): void => { if (this.pending.get(name) === task) this.pending.delete(name); };
        void task.then(clear, clear);
        return task;
    }
    private loadBundleSource(source: string, options: { version?: string }): Promise<AssetManager.Bundle> {
        return new Promise<AssetManager.Bundle>((resolve, reject) => {
            const started = Date.now();
            assetManager.loadBundle(source, options, (error, bundle) => {
                const cost = Date.now() - started;
                if (error) {
                    reject(new Error(`${error.message} (${cost}ms)`));
                    return;
                }
                if (!bundle) {
                    reject(new Error(`引擎未返回资源包 (${cost}ms)`));
                    return;
                }
                resolve(bundle);
            });
        });
    }
    loadScene(bundleName: string, sceneName: string, progress?: LoadProgress): Promise<SceneAsset> {
        return this.withBundleRetry(bundleName, bundle => new Promise<SceneAsset>((resolve, reject) => {
            bundle.loadScene(sceneName, (finished, total) => progress?.(finished, total),
                (error, scene) => error ? reject(error) : resolve(scene));
        }));
    }
    private async ensureDependencies(dependencies: readonly string[]): Promise<void> {
        const unique = Array.from(new Set(dependencies));
        for (const dependency of unique) {
            await this.bundle(dependency);
            if (!assetManager.getBundle(dependency))
                throw new Error(`资源包依赖未注册：${dependency}`);
        }
    }
    /**
     * WeChat resolves redirected assets after a bundle has loaded. If its subpackage
     * registration is briefly unavailable, load the named dependency once and retry.
     */
    private async withBundleRetry<T>(bundleName: string, load: (bundle: AssetManager.Bundle) => Promise<T>): Promise<T> {
        const recovered = new Set<string>();
        for (;;) {
            try {
                return await load(await this.bundle(bundleName));
            } catch (error) {
                const dependency = missingBundle(error);
                if (!dependency || recovered.has(dependency)) throw error;
                recovered.add(dependency);
                console.warn(`[Res] ${bundleName} requires ${dependency}; loading dependency and retrying`);
                await this.bundle(dependency);
            }
        }
    }
    private async loadAsset<T extends Asset>(bundleName: string, path: string, type: Constructor<T>, progress?: LoadProgress,
        priority: LoadPriority = 'normal', cancelled?: () => boolean): Promise<T> {
        const key = `${bundleName}:${path}`;
        let pending = this.assets.get(type);
        if (!pending) { pending = new Map(); this.assets.set(type, pending); }
        const shared = pending.get(key);
        if (shared) {
            if (cancelled) shared.cancellations.add(cancelled);
            try {
                const asset = await shared.promise as T;
                progress?.(1, 1);
                return asset;
            } finally {
                if (cancelled) shared.cancellations.delete(cancelled);
            }
        }
        const cancellations = new Set<() => boolean>();
        if (cancelled) cancellations.add(cancelled);
        const created: SharedAssetLoad = {
            cancellations,
            promise: this.queue.schedule(async () => {
                return this.withBundleRetry(bundleName, bundle => {
                    const cached = bundle.get(path, type);
                    if (cached) { progress?.(1, 1); return Promise.resolve(cached); }
                    return new Promise<T>((resolve, reject) => bundle.load(path, type,
                        (finished, total) => progress?.(finished, total),
                        (error, asset) => error ? reject(error) : resolve(asset)));
                });
            }, priority, () => cancellations.size > 0 && Array.from(cancellations).every(test => test())),
        };
        pending.set(key, created);
        try { return await created.promise as T; }
        finally {
            if (cancelled) cancellations.delete(cancelled);
            if (pending.get(key) === created) pending.delete(key);
        }
    }
}
